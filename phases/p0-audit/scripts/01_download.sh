if [[ "$INCLUDE_VAIHINGEN" == "1" ]]; then
  if vaihingen_url="$(resolve_vaihingen_raw_url)"; then
    download_file \
      "Auxiliary Vaihingen (ISPRS UrbanSemLab)" \
      "$vaihingen_url" \
      "isprs/Vaihingen.zip" \
      "ISPRS benchmark terms of use" \
      "Password-protected Seafile share resolved from public ISPRS UrbanSemLab link." \
      "16016774527" \
      "https://seafile.projekt.uni-hannover.de/f/6a06a837b1f349cfa749/"
  else
    local_reason="could not resolve password-protected Seafile rawPath"
    record_failure "Auxiliary Vaihingen -> isprs/Vaihingen.zip" "https://seafile.projekt.uni-hannover.de/f/6a06a837b1f349cfa749/" "$local_reason"
    append_row "Auxiliary Vaihingen (ISPRS UrbanSemLab)" "isprs/Vaihingen.zip" "failed" "-" "-" "ISPRS benchmark terms of use" "https://seafile.projekt.uni-hannover.de/f/6a06a837b1f349cfa749/" "$local_reason"
  fi
else
  append_row "Auxiliary Vaihingen (ISPRS UrbanSemLab)" "isprs/Vaihingen.zip" "skipped" "-" "-" "ISPRS benchmark terms of use" "https://seafile.projekt.uni-hannover.de/f/6a06a837b1f349cfa749/" "Set INCLUDE_VAIHINGEN=1 to download the 16GB auxiliary dataset."
fi

if [[ -s "${tmp_failures}" ]]; then
  {
    printf '\n## Failed Or Fallback URLs\n\n'
    cat "${tmp_failures}"
  } >> "${tmp_inventory}"

  {
    printf '# P0 Issues\n\n'
    printf '## T1 Data Download\n\n'
    cat "${tmp_failures}"
  } > "${ISSUES}"
else
  rm -f "${ISSUES}"
fi

mv "${tmp_inventory}" "${INVENTORY}"
printf 'Wrote %s\n' "$INVENTORY"
