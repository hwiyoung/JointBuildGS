    "CC BY 4.0; attribution: Bayerische Vermessungsverwaltung - www.geodaten.bayern.de" \
    "TUM2TWIN ALS tile; EPSG:25832 LAZ."
done

for tile in 690_5334 690_5336; do
  download_file \
    "LoD2 reference (Bayern CityGML)" \
    "https://download1.bayernwolke.de/a/lod2/citygml/${tile}.gml" \
    "lod2/${tile}.gml" \
    "CC BY 4.0; attribution: Bayerische Vermessungsverwaltung - www.geodaten.bayern.de" \
    "TUM2TWIN LoD2 tile; CityGML 2.0."
