"${compose[@]}" build tools

download_file \
  "UAV images (Zenodo 14548134)" \
  "https://zenodo.org/records/14548134/files/Images.zip" \
  "uav/Images.zip" \
  "CC BY 4.0" \
  "TUM2TWIN UAS photographs; AGENTS.md section 5." \
  "5906891973"

download_with_fallback \
  "UAV OPF poses (Zenodo)" \
  "https://zenodo.org/records/14548134/files/opf.zip" \
  "https://zenodo.org/records/14899378/files/opf.zip" \
  "uav/opf.zip" \
  "CC BY 4.0" \
  "AGENTS.md names record 14548134; current opf.zip is available from Zenodo record 14899378." \
  "1936493976"

for tile in 690_5335 690_5336 691_5335 691_5336; do
  download_file \
    "ALS point cloud (Bayern Laserdaten)" \
    "https://geodaten.bayern.de/odd_data/laser/${tile}.laz" \
