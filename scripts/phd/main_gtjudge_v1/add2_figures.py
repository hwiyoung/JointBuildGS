def wall(site,prior):
    stem=f'{site}__{prior}';root=O/'scenes'/stem;path=D/'figures/addendum2'/f'{stem}_wall_mesh_views.png'
    if path.exists():return
    row=loadz(root/'rows.npz');a=loadz(root/'distances/FINALTRAIN_30000.npz',['row_s'])['row_s'];b=loadz(root/'distances/baseline_30000.npz',['row_s'])['row_s'];tau=row['row_tau_m']
    mask=row['wall']&(~np.isfinite(a)|(abs(a)>tau))&np.isfinite(b)&(abs(b)<=tau);ids=np.flatnonzero(mask)
    if not len(ids):dump(path.with_suffix('.json'),dict(status='UNAVAILABLE_NO_WALL_COMPONENT',scientific_verdict=None));return
    P=row['xyz'][ids];pairs=cKDTree(P).query_pairs(.6,output_type='ndarray');g=coo_matrix((np.ones(len(pairs)),(pairs[:,0],pairs[:,1])),shape=(len(P),len(P)));_,lab=connected_components(g,directed=False);chosen=np.argmax(np.bincount(lab));P=P[lab==chosen]
    lo=P[:,:2].min(0);hi=P[:,:2].max(0);sec=dict(status='PASS',start=lo.tolist(),end=hi.tolist())
    reader=f.loadz
    missing=root/'distances/baseline_30000_samples.npz'
    def inherited_samples(path,*args,**kwargs):
        if Path(path)==missing:return {'xyz':reader(score_dir(site,prior,'baseline_30000')/'points.npz',['sample_xyz'])['sample_xyz']}
        return reader(path,*args,**kwargs)
    f.loadz=inherited_samples
    try:f.multiview(site,prior,'add2_wall',['FINALTRAIN_30000','baseline_30000'],sec,[root/'rows.npz'])
    finally:f.loadz=reader
    # Keep generated bytes; move only this new, specifically requested figure and metadata.
    for ext in ['.png','.json']:(D/'figures'/f'{stem}_add2_wall_mesh_views{ext}').rename(path.with_suffix(ext))
    meta=json.loads(path.with_suffix('.json').read_text());meta.update(component_gt_points=len(P),component_radius_m=.6,selection='wall GT: FINALTRAIN wrong and baseline right, largest connected component');dump(path.with_suffix('.json'),meta)

