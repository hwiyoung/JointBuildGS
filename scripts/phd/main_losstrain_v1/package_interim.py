def stable_bytes(path):
    """Avoid torn reads of reports being atomically replaced or rewritten."""
    for _ in range(10):
        before = path.stat()
        data = path.read_bytes()
        after = path.stat()
        if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
            time.sleep(.1)
            continue
        try:
            if path.suffix == '.json':
                json.loads(data)
            if path.suffix == '.jsonl':
                for line in data.splitlines():
                    if line.strip():
                        json.loads(line)
        except (ValueError, UnicodeDecodeError):
            time.sleep(.1)
            continue
        return data
    raise RuntimeError(f'Unable to snapshot changing file: {path}')


