"""Source headers and explicit existing/absent input inventory, CPU only."""
import json
from pathlib import Path
import laspy
import numpy as np
from analysis_common import O,DOC,save_table
from preflight import PH,PREP,sha
RAW=Path('/art/phase-payloads/p0-audit/data/raw');S0=PH/'main_stage0_v1/PHD-MAIN-STAGE0-v1';S1=PH/'main_stage1_v1/PHD-MAIN-STAGE1-v1'
def main():
    rows=[]
    for p in [RAW/'tum2twin/TUM_Downtown_ULS_20241217_nadir.laz']+sorted((RAW/'als').glob('*.laz')):
        with laspy.open(p) as f:
            h=f.header
            rows.append(dict(source=str(p),points=h.point_count,bounds_min_epsg25832=h.mins.tolist(),bounds_max_epsg25832=h.maxs.tolist(),
                header_creation_date=str(h.creation_date),scale=h.scales.tolist(),offset=h.offsets.tolist(),generating_software=h.generating_software,
                measurement_date='2024-12-17' if p.parent.name=='tum2twin' else '2022-02-27',
                date_source='nadir filename and existing data inventory' if p.parent.name=='tum2twin' else '/repo/docs/evidence/p0-audit/w1-input-diagnostics/reports/data_inventory.md:26 (adjusted GPS time)',
                source_sha256=json.loads((O/'scope_split.json').read_text())['raw_sources'][str(p)]['sha256']))
    save_table('원자료_머리글',rows)
    inventory=[]
    for site in ['B0_b10','B173nb_b10','B173_b0','R1rep_b10']:
        m=S0/'fork_inputs/s61'/site/'maps'
        for label,p,pattern in [('MVS geometric',PREP/'mvs'/('box_'+site)/'stereo/depth_maps','*.geometric.bin'),
            ('confidence mask',m/'conf','*.npy'),('prior render LoD2',m/'prior_LoD2','*.npy'),('prior render ALS',m/'prior_ALS','*.npy'),
            ('regions',S1/'regions_v3',f'*{site}*'),('patch values',PH/'main_uncert_v1/PHD-MAIN-UNCERT-v1/patch_values',f'{site}__*__R1.5.npz')]:
            files=list(p.glob(pattern));inventory.append(dict(scope=site,input=label,files=len(files),source=str(p),pattern=pattern,existed_before_task=True))
    for label in ['MVS geometric','confidence mask','prior render LoD2','prior render ALS','regions','patch values']:
        inventory.append(dict(scope='full frozen 819-image training split',input=label,files_before_task=0,
            status='new geometric depths and validity>0 mask generated by this task' if label in ['MVS geometric','confidence mask'] else
            ('new patch values generated by this task' if label=='patch values' else 'not generated; registration renders transiently, no method region codes'),
            note='Historical 937-image full MVS includes evaluation views and is inventory only.'))
    save_table('입력_있음없음',inventory)
    print('source headers and availability inventory complete')
if __name__=='__main__':main()
