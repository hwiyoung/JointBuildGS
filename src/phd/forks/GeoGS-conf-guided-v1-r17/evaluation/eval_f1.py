"""
Compute Precision and F-score for Traditional Completeness, then append to
existing statistics.txt generated by eval_full.py.

Uses the same downsampling and thresholds as eval_full.py for consistency.

Usage:
    python evaluation/eval_f1.py \
        --gt_path <gt.ply> \
        --eval_path <eval.ply> \
        --output_root <eval_results_dir>
"""

import argparse
import os
import numpy as np
from scipy.spatial import cKDTree
from plyfile import PlyData


def load_ply_points(path):
    ply = PlyData.read(path)
    v = ply['vertex']
    return np.vstack([v['x'], v['y'], v['z']]).T.astype(np.float64)


def voxel_downsample(pts, voxel_size):
    voxel_idx = np.floor(pts / voxel_size).astype(np.int64)
    _, unique_idx = np.unique(voxel_idx, axis=0, return_index=True)
    return pts[unique_idx].copy()


def make_output_dir(output_root, eval_path):
    """Same logic as eval_full.py to find the existing output folder."""
    basename = os.path.splitext(os.path.basename(eval_path))[0]
    parent = os.path.basename(os.path.dirname(eval_path))
    if 'pcd' in parent.lower():
        prefix = 'pcd'
    elif 'mesh' in parent.lower():
        prefix = 'mesh'
    else:
        prefix = 'eval'
    folder = f"{prefix}_{basename}"
    return os.path.join(output_root, folder)


def parse_args():
    p = argparse.ArgumentParser(description='Compute Precision & F-score, append to statistics.txt')
    p.add_argument('--gt_path', type=str,
                   default='./evaluation_data/example_ply/gt_transformed.ply')
    p.add_argument('--eval_path', type=str,
                   default='./evaluation_data/example_ply/pred.ply')
    p.add_argument('--output_root', type=str,
                   default='./evaluation_data/results')
    p.add_argument('--downsample_voxel', type=float, default=0.1)
    p.add_argument('--completeness_thresholds', type=float, nargs='+',
                   default=[0.1, 0.2, 0.5])
    return p.parse_args()


def main():
    args = parse_args()

    out_dir = make_output_dir(args.output_root, args.eval_path)
    stats_path = os.path.join(out_dir, 'statistics.txt')

    if not os.path.isfile(stats_path):
        print(f"ERROR: statistics.txt not found at {stats_path}")
        return

    # Check if already appended
    with open(stats_path, 'r') as f:
        existing = f.read()
    if 'Precision & F-score' in existing:
        print(f"  SKIP (already computed): {out_dir}")
        return

    # Load and downsample
    print(f"  Loading point clouds...")
    gt_pts = load_ply_points(args.gt_path)
    eval_pts = load_ply_points(args.eval_path)

    if args.downsample_voxel > 0:
        gt_ds = voxel_downsample(gt_pts, args.downsample_voxel)
        eval_ds = voxel_downsample(eval_pts, args.downsample_voxel)
    else:
        gt_ds = gt_pts
        eval_ds = eval_pts

    # Compute distances in both directions
    tree_eval = cKDTree(eval_ds)
    tree_gt = cKDTree(gt_ds)
    d_gt2eval, _ = tree_eval.query(gt_ds)   # completeness direction
    d_eval2gt, _ = tree_gt.query(eval_ds)   # precision direction

    # Compute metrics per threshold
    results = {}
    for t in args.completeness_thresholds:
        comp = float(np.mean(d_gt2eval < t))
        prec = float(np.mean(d_eval2gt < t))
        f1 = 2 * comp * prec / (comp + prec) if (comp + prec) > 0 else 0.0
        results[t] = (comp, prec, f1)

    # Print results
    for t, (comp, prec, f1) in results.items():
        print(f"  @{t}m: Comp={comp*100:.2f}%, Prec={prec*100:.2f}%, F={f1*100:.2f}%")

    # Append to statistics.txt
    with open(stats_path, 'a') as f:
        f.write("\n------------------------------------------------------------\n")
        f.write("Precision & F-score (Tanks & Temples style)\n")
        f.write("------------------------------------------------------------\n")
        if args.downsample_voxel > 0:
            f.write(f"Downsampling: voxel_size={args.downsample_voxel} m\n")
            f.write(f"  GT:   {len(gt_pts)} -> {len(gt_ds)} points\n")
            f.write(f"  Eval: {len(eval_pts)} -> {len(eval_ds)} points\n\n")
        else:
            f.write(f"Downsampling: disabled\n\n")

        f.write(f"{'Threshold':>12s}  {'Completeness':>12s}  {'Precision':>12s}  {'F-score':>12s}\n")
        for t, (comp, prec, f1) in results.items():
            f.write(f"{t:>10.2f}m  {comp*100:>11.2f}%  {prec*100:>11.2f}%  {f1*100:>11.2f}%\n")

        f.write("\n============================================================\n")

    print(f"  Appended to: {stats_path}")


if __name__ == '__main__':
    main()
